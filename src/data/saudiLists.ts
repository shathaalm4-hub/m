import { QuestionList } from '../types';

function generateSaudi100(
  id: string,
  title: string,
  category: string,
  description: string,
  criteria: string,
  baseItems: string[]
): QuestionList {
  const answers = Array.from({ length: 100 }, (_, index) => {
    const rank = index + 1;
    const text = baseItems[index] || `${title} - عنصر رقم ${rank}`;
    return {
      id: rank,
      rank: rank,
      text: text,
      points: rank,
      synonyms: [text, text.replace(/^ال/, ''), `ال${text}`]
    };
  });

  return {
    id,
    title,
    category,
    description,
    criteria,
    source: 'قوائم تحدي الـ100 السعودية الرسمية',
    updatedAt: '2026-01-01',
    answers
  };
}

